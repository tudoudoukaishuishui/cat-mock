function assertCatalog() {
  const courseIds = new Set(courses.map((course) => course.id));
  const coachIds = new Set(coaches.map((coach) => coach.id));
  const studioIds = new Set(studios.map((studio) => studio.id));
  const sessionIds = new Set<string>();

  for (const session of sessions) {
    if (sessionIds.has(session.id)) throw new Error(`场次编号重复：${session.id}`);
    sessionIds.add(session.id);
    if (!courseIds.has(session.courseId)) throw new Error(`场次缺少课程：${session.id}`);
    if (!coachIds.has(session.coachId)) throw new Error(`场次缺少教练：${session.id}`);
    if (!studioIds.has(session.studioId)) throw new Error(`场次缺少场地：${session.id}`);
    if (session.booked < 0 || session.booked > session.capacity) {
      throw new Error(`名额不合理：${session.id}`);
    }
    if (new Date(session.end).getTime() <= new Date(session.start).getTime()) {
      throw new Error(`时间不合理：${session.id}`);
    }
    const course = courses.find((item) => item.id === session.courseId);
    if (!course) continue;
    const minutes = (new Date(session.end).getTime() - new Date(session.start).getTime()) / 60000;
    if (minutes !== course.durationMinutes) {
      throw new Error(`时长与课程不符：${session.id} ${minutes} != ${course.durationMinutes}`);
    }
  }
}

